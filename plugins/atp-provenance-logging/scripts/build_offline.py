#!/usr/bin/env python3
"""Build ui/prove-offline.html: the whole dashboard in one file.

React (vendored), app.css and app.js are inlined so the page works when it is
copied anywhere on its own and opened straight from disk (file://), with no
server and no network. Live mode needs the service, so from a file:// page use
Import JSON (an export from GET /chain or `prove_local.py export`) and
Simulate. Re-run after syncing ui/app.js or ui/app.css from Prove:

    python3 scripts/build_offline.py          # writes ui/prove-offline.html
    python3 scripts/build_offline.py --check  # exit 1 if the file is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

UI = Path(__file__).resolve().parent.parent / "ui"
OUT = UI / "prove-offline.html"


def _safe(text: str, closing: str) -> str:
    if closing in text.lower():
        raise SystemExit(f"refusing to inline: source contains {closing}")
    return text


def build() -> str:
    page = (UI / "index.html").read_text()
    css = _safe((UI / "app.css").read_text(), "</style")
    scripts = {
        name: _safe((UI / name).read_text(), "</script")
        for name in ("vendor/react.production.min.js", "vendor/react-dom.production.min.js", "app.js")
    }
    page = page.replace('<link rel="stylesheet" href="app.css">', f"<style>\n{css}\n</style>")
    for name, body in scripts.items():
        tag = f'<script src="{name}"></script>'
        if tag not in page:
            raise SystemExit(f"index.html no longer references {name}")
        page = page.replace(tag, f"<script>/* {name} */\n{body}\n</script>")
    page = page.replace(
        "<!-- Network-free build",
        "<!-- GENERATED by scripts/build_offline.py from index.html; do not edit.\n"
        "     Single-file network-free build",
        1,
    )
    if re.search(r"(src|href)\s*=\s*\"https?://", page):
        raise SystemExit("offline page references a network URL")
    return page


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    page = build()
    if a.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != page:
            print("ui/prove-offline.html is stale; run scripts/build_offline.py", file=sys.stderr)
            return 1
        print("ui/prove-offline.html is current")
        return 0
    OUT.write_text(page)
    print(f"wrote {OUT} ({len(page.encode()) // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
